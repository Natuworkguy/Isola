import AppKit
import CryptoKit
import ImageIO
import SwiftUI

struct ClipboardEntry: Identifiable, Codable, Equatable {
    enum Kind: String, Codable {
        case text, link, color, image
    }

    let id: UUID
    let kind: Kind
    /// The text, the link, the colour's hex code, or for an image its file name in the clipboard store.
    let text: String
    let date: Date
    /// An image's size in pixels, such as "1280×720".
    var pixelSize: String?

    init(kind: Kind, text: String, pixelSize: String? = nil) {
        id = UUID()
        self.kind = kind
        self.text = text
        date = Date()
        self.pixelSize = pixelSize
    }

    /// History saved before there were kinds is all text; links and colours in it are recognised again.
    init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        id = try container.decode(UUID.self, forKey: .id)
        text = try container.decode(String.self, forKey: .text)
        date = try container.decodeIfPresent(Date.self, forKey: .date) ?? Date()
        kind = try container.decodeIfPresent(Kind.self, forKey: .kind) ?? ClipboardMonitor.classify(text)
        pixelSize = try container.decodeIfPresent(String.self, forKey: .pixelSize)
    }

    var searchText: String {
        kind == .image ? "image picture photo \(pixelSize ?? "")" : text
    }
}

final class ClipboardMonitor: ObservableObject {
    @Published private(set) var entries: [ClipboardEntry] = []

    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private let storeKey = "clipboardHistory"
    private let thumbnails: NSCache<NSString, NSImage> = {
        let cache = NSCache<NSString, NSImage>()
        cache.countLimit = 60
        return cache
    }()

    /// Images larger than this, as PNG, are not kept.
    private static let maxImageBytes = 25_000_000
    /// Text longer than this is not kept: the whole history is saved on every copy.
    private static let maxTextLength = 100_000
    /// The cards are small, so a picture is read at most this many pixels on its long side. Read whole, a 5K
    /// screenshot is around 60 MB in memory, and the history holds dozens.
    private static let thumbnailPixels = 480

    private let skippedTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    static var imageFolder: URL {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        return base.appendingPathComponent("Isola/Clipboard", isDirectory: true)
    }

    func start() {
        load()
        NotificationCenter.default.addObserver(forName: .isolaTrimMemory, object: nil, queue: .main) { [weak self] _ in
            self?.thumbnails.removeAllObjects()
        }
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.poll()
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    // MARK: Recording

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = pasteboard.types ?? []
        guard !types.contains(where: { skippedTypes.contains($0) }) else { return }

        let string = pasteboard.string(forType: .string)
        let trimmed = string?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""

        // Copied files carry their icon as an image; that is not a picture anyone copied.
        let copiedFiles = types.contains(.fileURL)
        if !copiedFiles, trimmed.isEmpty || Self.classify(trimmed) == .link {
            if let png = pasteboard.data(forType: .png) {
                addImage(png, isPNG: true)
                return
            }
            if let tiff = pasteboard.data(forType: .tiff) {
                addImage(tiff, isPNG: false)
                return
            }
        }

        guard let string, !trimmed.isEmpty, string.count <= Self.maxTextLength else { return }
        add(kind: Self.classify(trimmed), text: string)
    }

    static func classify(_ text: String) -> ClipboardEntry.Kind {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if trimmed.range(of: "^#([0-9a-fA-F]{3}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$", options: .regularExpression) != nil {
            return .color
        }
        if trimmed.count < 2048, !trimmed.contains(where: { $0.isWhitespace }),
           let url = URL(string: trimmed), let scheme = url.scheme?.lowercased(),
           scheme == "http" || scheme == "https", url.host != nil {
            return .link
        }
        return .text
    }

    private func addImage(_ data: Data, isPNG: Bool) {
        DispatchQueue.global(qos: .utility).async { [weak self] in
            guard let rep = NSBitmapImageRep(data: data),
                  let png = isPNG ? data : rep.representation(using: .png, properties: [:]),
                  png.count <= Self.maxImageBytes else { return }

            // Named after its contents, so copying the same picture twice keeps one file.
            let name = SHA256.hash(data: png).prefix(12).map { String(format: "%02x", $0) }.joined() + ".png"
            let folder = Self.imageFolder
            let url = folder.appendingPathComponent(name)
            if !FileManager.default.fileExists(atPath: url.path) {
                try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true,
                                                         attributes: [.posixPermissions: 0o700])
                guard (try? png.write(to: url, options: .atomic)) != nil else { return }
            }
            let size = "\(rep.pixelsWide)×\(rep.pixelsHigh)"
            DispatchQueue.main.async { self?.add(kind: .image, text: name, pixelSize: size) }
        }
    }

    private func add(kind: ClipboardEntry.Kind, text: String, pixelSize: String? = nil) {
        withAnimation(.easeInOut(duration: 0.2)) {
            entries.removeAll { $0.kind == kind && $0.text == text }
            entries.insert(ClipboardEntry(kind: kind, text: text, pixelSize: pixelSize), at: 0)
            let limit = max(UserDefaults.standard.integer(forKey: Prefs.clipboardLimit), 1)
            if entries.count > limit { entries.removeLast(entries.count - limit) }
        }
        save()
    }

    // MARK: Using

    func imageURL(_ entry: ClipboardEntry) -> URL? {
        entry.kind == .image ? Self.imageFolder.appendingPathComponent(entry.text) : nil
    }

    /// A small copy of an image entry, for showing it. Copying it back uses the full picture.
    func image(_ entry: ClipboardEntry) -> NSImage? {
        guard let url = imageURL(entry) else { return nil }
        let key = entry.text as NSString
        if let cached = thumbnails.object(forKey: key) { return cached }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceShouldCacheImmediately: true,
            kCGImageSourceThumbnailMaxPixelSize: Self.thumbnailPixels,
        ]
        guard let source = CGImageSourceCreateWithURL(url as CFURL, nil),
              let thumbnail = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        let image = NSImage(cgImage: thumbnail, size: NSSize(width: thumbnail.width, height: thumbnail.height))
        thumbnails.setObject(image, forKey: key)
        return image
    }

    func copy(_ entry: ClipboardEntry) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch entry.kind {
        case .image:
            if let url = imageURL(entry), let image = NSImage(contentsOf: url) { pasteboard.writeObjects([image]) }
        case .link:
            let link = entry.text.trimmingCharacters(in: .whitespacesAndNewlines)
            pasteboard.setString(link, forType: .string)
            pasteboard.setString(link, forType: .URL)
        case .text, .color:
            pasteboard.setString(entry.text, forType: .string)
        }
        // Our own write: not recorded again, and the list stays put so the card under the pointer does not move.
        lastChangeCount = pasteboard.changeCount
    }

    func remove(_ entry: ClipboardEntry) {
        withAnimation(.easeInOut(duration: 0.2)) { entries.removeAll { $0.id == entry.id } }
        save()
    }

    func clear() {
        entries.removeAll()
        save()
    }

    // MARK: Storage

    private func load() {
        guard let data = UserDefaults.standard.data(forKey: storeKey),
              let saved = try? JSONDecoder().decode([ClipboardEntry].self, from: data) else { return }
        entries = saved
        pruneImages()
    }

    private func save() {
        if let data = try? JSONEncoder().encode(entries) {
            UserDefaults.standard.set(data, forKey: storeKey)
        }
        pruneImages()
    }

    /// Deletes stored images that no entry uses any more. A file under a minute old is left alone: it may be a
    /// picture just copied whose entry is still on its way.
    private func pruneImages() {
        let kept = Set(entries.filter { $0.kind == .image }.map(\.text))
        DispatchQueue.global(qos: .utility).async {
            let manager = FileManager.default
            let folder = Self.imageFolder
            guard let files = try? manager.contentsOfDirectory(atPath: folder.path) else { return }
            for file in files where file.hasSuffix(".png") && !kept.contains(file) {
                let url = folder.appendingPathComponent(file)
                let modified = (try? manager.attributesOfItem(atPath: url.path)[.modificationDate]) as? Date
                guard Date().timeIntervalSince(modified ?? .distantPast) > 60 else { continue }
                try? manager.removeItem(at: url)
            }
        }
    }

    // MARK: Colours

    static func rgb(_ hex: String) -> (red: Double, green: Double, blue: Double)? {
        var digits = hex.trimmingCharacters(in: .whitespacesAndNewlines)
        if digits.hasPrefix("#") { digits.removeFirst() }
        if digits.count == 3 { digits = digits.map { "\($0)\($0)" }.joined() }
        if digits.count == 8 { digits = String(digits.prefix(6)) }
        guard digits.count == 6, let value = UInt32(digits, radix: 16) else { return nil }
        return (Double((value >> 16) & 0xFF) / 255, Double((value >> 8) & 0xFF) / 255, Double(value & 0xFF) / 255)
    }
}
